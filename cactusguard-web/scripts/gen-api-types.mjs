/**
 * Gera `src/api/generated/schema.d.ts` a partir de `src/api/openapi.json` (OpenAPI real do backend).
 *   node scripts/gen-api-types.mjs          grava o arquivo
 *   node scripts/gen-api-types.mjs --check  falha (exit 1) se o arquivo gerado estiver desatualizado
 * O teste `src/api/contract.test.ts` usa `renderSchema()` para a mesma verificação.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'

// caminhos relativos à raiz do projeto (npm run e vitest executam a partir dela)
const SPEC = resolve(process.cwd(), 'src/api/openapi.json')
export const OUT = resolve(process.cwd(), 'src/api/generated/schema.d.ts')
const HEADER = '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n'

export async function renderSchema() {
  const ast = await openapiTS(JSON.parse(readFileSync(SPEC, 'utf8')))
  return HEADER + astToString(ast)
}

const normalize = (s) => s.replace(/\r\n/g, '\n')

if (process.argv[1]?.replaceAll('\\', '/').endsWith('scripts/gen-api-types.mjs')) {
  const out = await renderSchema()
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(OUT, 'utf8')
    } catch {
      /* arquivo ausente = desatualizado */
    }
    if (normalize(current) !== normalize(out)) {
      process.stderr.write('Tipos gerados desatualizados em relação a src/api/openapi.json. Rode: npm run api:types\n')
      process.exit(1)
    }
    process.stdout.write('Tipos gerados estão em dia.\n')
  } else {
    writeFileSync(OUT, out)
    process.stdout.write(`Gerado ${OUT}\n`)
  }
}
