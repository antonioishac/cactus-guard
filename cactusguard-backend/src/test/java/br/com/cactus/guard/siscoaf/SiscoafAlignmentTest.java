package br.com.cactus.guard.siscoaf;

import br.com.cactus.guard.auth.entity.User;
import br.com.cactus.guard.auth.repository.UserRepository;
import br.com.cactus.guard.case_.entity.Case;
import br.com.cactus.guard.case_.repository.CaseRepository;
import br.com.cactus.guard.common.exception.BusinessException;
import br.com.cactus.guard.party.entity.Party;
import br.com.cactus.guard.party.repository.PartyRepository;
import br.com.cactus.guard.siscoaf.dto.SiscoafResponse;
import br.com.cactus.guard.siscoaf.repository.SiscoafSpecifications;
import br.com.cactus.guard.siscoaf.service.SiscoafService;
import br.com.cactus.guard.support.TestUsers;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.data.domain.PageRequest;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.test.context.ActiveProfiles;

import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@ActiveProfiles("test")
class SiscoafAlignmentTest {

    private static final String JUST = "Operacoes incompativeis com a capacidade financeira declarada";

    @Autowired private SiscoafService siscoafService;
    @Autowired private CaseRepository caseRepository;
    @Autowired private PartyRepository partyRepository;
    @Autowired private UserRepository userRepository;

    private User creator;
    private User decider;
    private User approver;

    @BeforeEach
    void users() {
        creator = TestUsers.ensure(userRepository, TestUsers.unique("creator"));
        decider = TestUsers.ensure(userRepository, TestUsers.unique("decider"));
        approver = TestUsers.ensure(userRepository, TestUsers.unique("approver"));
    }

    @AfterEach
    void logout() {
        TestUsers.logout();
    }

    private Case communicateCase(boolean pep) {
        Party p = partyRepository.save(Party.builder().type("PF")
                .document(UUID.randomUUID().toString().replace("-", "").substring(0, 11))
                .name("Parte Siscoaf").status("ACTIVE").pep(pep).riskLevel(pep ? "HIGH" : "LOW").build());
        return caseRepository.save(Case.builder().party(p).status("COMMUNICATE").decision("COMMUNICATE")
                .decidedBy(decider).decidedAt(Instant.now()).approvedBy(approver).approvedAt(Instant.now())
                .selectedAt(Instant.now()).analysisDeadline(Instant.now().plusSeconds(86400L * 40)).build());
    }

    private SiscoafResponse draft(Case c, User by) {
        TestUsers.login(by.getUsername(), "SUPERVISOR");
        return siscoafService.createDraft(c.getId(), "COS", Map.of("k", "v"));
    }

    @Test
    void approveRequiresSupervisorAndJustification() {
        Case c = communicateCase(false);
        SiscoafResponse d = draft(c, creator);
        TestUsers.login(creator.getUsername(), "ANALYST");
        assertThrows(AccessDeniedException.class, () -> siscoafService.approve(d.getId(), JUST));
        TestUsers.login(approver.getUsername(), "SUPERVISOR");
        assertThrows(BusinessException.class, () -> siscoafService.approve(d.getId(), "curta"));
        assertThrows(BusinessException.class, () -> siscoafService.approve(d.getId(), null));
    }

    @Test
    void fourEyesBlocksCreatorAndCaseDeciderForPepParty() {
        Case c = communicateCase(true);
        SiscoafResponse d = draft(c, creator);

        TestUsers.login(creator.getUsername(), "SUPERVISOR");
        assertThrows(BusinessException.class, () -> siscoafService.approve(d.getId(), JUST));
        TestUsers.login(decider.getUsername(), "SUPERVISOR");
        assertThrows(BusinessException.class, () -> siscoafService.approve(d.getId(), JUST));

        TestUsers.login(approver.getUsername(), "SUPERVISOR");
        SiscoafResponse ok = siscoafService.approve(d.getId(), JUST);
        assertEquals("APPROVED", ok.getStatus());
        assertEquals(approver.getId(), ok.getApprovedById());
    }

    @Test
    void draftAutoGeneratedAtCaseApprovalCanBeApprovedByCaseApproverButNotByDecider() {
        Case c = communicateCase(true); // aprovador do case = approver
        SiscoafResponse d = draft(c, approver); // criador == aprovador do case (rascunho automatico)
        TestUsers.login(decider.getUsername(), "SUPERVISOR");
        assertThrows(BusinessException.class, () -> siscoafService.approve(d.getId(), JUST));
        TestUsers.login(approver.getUsername(), "SUPERVISOR");
        assertEquals("APPROVED", siscoafService.approve(d.getId(), JUST).getStatus());
    }

    @Test
    void sensitiveCommunicationCannotBeSubmittedWithoutPriorApproval() {
        Case c = communicateCase(true);
        SiscoafResponse d = draft(c, creator);
        TestUsers.login(approver.getUsername(), "SUPERVISOR");
        assertThrows(BusinessException.class, () -> siscoafService.submit(d.getId(), JUST));
        siscoafService.approve(d.getId(), JUST);
        assertEquals("SUBMITTED", siscoafService.submit(d.getId(), JUST).getStatus());
    }

    @Test
    void nonSensitiveCommunicationKeepsCreatorApprovalAndSubmitWritesJustificationToHistory() {
        Case c = communicateCase(false);
        SiscoafResponse d = draft(c, creator);
        // sem quatro olhos: o proprio criador (SUPERVISOR) pode aprovar
        assertEquals("APPROVED", siscoafService.approve(d.getId(), JUST).getStatus());
        TestUsers.login(approver.getUsername(), "SUPERVISOR");
        String reason = "Envio autorizado conforme analise do comite de PLD";
        siscoafService.submit(d.getId(), reason);

        SiscoafResponse detail = siscoafService.findById(d.getId());
        assertEquals("SUBMITTED", detail.getStatus());
        var actions = detail.getStatusHistory().stream().map(h -> h.action()).toList();
        assertEquals(List.of("CREATED", "APPROVE", "SUBMIT"), actions);
        var submit = detail.getStatusHistory().get(2);
        assertEquals(reason, submit.reason());
        assertEquals("SUBMITTED", submit.status());
        assertEquals("APPROVED", submit.fromStatus());
        assertEquals(approver.getUsername(), submit.byName());
        assertEquals(creator.getId(), detail.getApprovedById()); // aprovador original preservado
    }

    @Test
    void submitWithShortReasonIsRejectedAndReasonIsOptional() {
        Case c = communicateCase(false);
        SiscoafResponse d = draft(c, creator);
        assertThrows(BusinessException.class, () -> siscoafService.submit(d.getId(), "curta"));
        assertEquals("SUBMITTED", siscoafService.submit(d.getId(), null).getStatus());
    }

    @Test
    void cancelAndFiltersExposeReasonOriginAndMultipleStatuses() {
        Case c = communicateCase(false);
        SiscoafResponse a = draft(c, creator);
        SiscoafResponse b = draft(c, creator);
        siscoafService.cancel(b.getId(), "Duplicidade detectada na revisao da comunicacao");

        var all = siscoafService.findAll(new SiscoafSpecifications.Filter(
                List.of("DRAFT", "CANCELLED"), List.of("COS"), null, null, null, c.getId()), PageRequest.of(0, 10));
        assertEquals(2, all.getTotalElements());
        var cancelled = all.getContent().stream().filter(r -> r.getId().equals(b.getId())).findFirst().orElseThrow();
        assertEquals("Duplicidade detectada na revisao da comunicacao", cancelled.getCancelReason());
        assertNotNull(cancelled.getCaseNumber() == null ? "" : cancelled.getCaseNumber());
        assertEquals("Parte Siscoaf", cancelled.getPartyName());
        assertNull(cancelled.getStatusHistory());

        var onlyDraft = siscoafService.findAll(new SiscoafSpecifications.Filter(
                List.of("DRAFT"), null, null, null, null, c.getId()), PageRequest.of(0, 10));
        assertEquals(List.of(a.getId()), onlyDraft.map(SiscoafResponse::getId).getContent());
        var none = siscoafService.findAll(new SiscoafSpecifications.Filter(
                null, List.of("COE"), null, null, null, c.getId()), PageRequest.of(0, 10));
        assertEquals(0, none.getTotalElements());
        var future = siscoafService.findAll(new SiscoafSpecifications.Filter(
                null, null, Instant.now().plusSeconds(3600), null, null, c.getId()), PageRequest.of(0, 10));
        assertEquals(0, future.getTotalElements());

        SiscoafResponse detail = siscoafService.findById(b.getId());
        assertEquals(List.of("CREATED", "CANCEL"), detail.getStatusHistory().stream().map(h -> h.action()).toList());
    }
}
