@Service
@RequiredArgsConstructor
public class SiscoafService {

    private static final Set<String> DRAFT_TYPES = Set.of("COS", "COE", "SAR", "COAF_COMMUNICATION");
    private static final Set<String> CANCELLABLE = Set.of("DRAFT", "PENDING_REVIEW", "APPROVED");
    private static final Set<String> APPROVABLE = Set.of("DRAFT", "PENDING_REVIEW");
    private static final Set<String> SENT = Set.of("SUBMITTED", "ACKNOWLEDGED");

    private final SiscoafCommunicationRepository repository;
    private final SiscoafHistoryRepository historyRepository;
    private final CaseRepository caseRepository;
    private final SiscoafOrchestrator orchestrator;
    private final AuditService auditService;
    private final CurrentUserService currentUser;

    @Transactional
    public SiscoafResponse createDraft(UUID caseId, String type, Map<String, Object> payload) {
        if (type == null || !DRAFT_TYPES.contains(type)) {
            throw new BusinessException("Tipo de comunicacao invalido: " + type
                    + " (declaracao negativa possui endpoint proprio)");
        }
        Case caseEntity = caseRepository.findById(caseId)
                .orElseThrow(() -> new IllegalArgumentException("Case not found"));

        SiscoafCommunication comm = SiscoafCommunication.builder()
                .caseEntity(caseEntity)
                .party(caseEntity.getParty())
                .type(type)
                .status("DRAFT")
                .payload(payload)
                .createdBy(currentUser.user().orElse(null))
                .build();

        comm = repository.save(comm);
        record(comm, "CREATED", null, "DRAFT", null);
        AuditPayload.log(auditService, "SISCOAF_DRAFT_CREATED", "SISCOAF_COMMUNICATION", comm.getId(), null,
                Map.of("type", type, "caseId", caseId.toString()));
        return toListResponse(comm);
    }

    /**
     * Aprovacao da comunicacao (acao de SUPERVISOR; justificativa obrigatoria). Quando exigido
     * (parte PEP, risco alto/critico ou case EDD) vale o quatro olhos: o aprovador deve ser diferente de
     * quem criou o rascunho e de quem decidiu o case. Aprovar NAO envia ao COAF.
     */
    @Transactional
    public SiscoafResponse approve(UUID id, String justification) {
        if (!currentUser.hasRole("SUPERVISOR")) {
            throw new AccessDeniedException("Aprovacao de comunicacao exige perfil SUPERVISOR");
        }
        String just = Justifications.require(justification, "aprovar comunicacao ao COAF");
        SiscoafCommunication comm = repository.findById(id)
                .orElseThrow(() -> new BusinessException("Communication not found"));
        if (!APPROVABLE.contains(comm.getStatus())) {
            throw new BusinessException("Comunicacao em status " + comm.getStatus() + " nao pode ser aprovada");
        }
        assertCosDecided(comm);
        User approver = currentUser.user()
                .orElseThrow(() -> new BusinessException("Aprovador nao identificado"));
        if (fourEyesRequired(comm)) {
            Case linked = comm.getCaseEntity();
            // Rascunho gerado automaticamente na aprovacao do case (criador = aprovador do case) nao e autoria
            // propria: a independencia ja foi garantida (aprovador do case != decisor); basta ser != decisor.
            boolean autoGenerated = linked != null && linked.getApprovedBy() != null && comm.getCreatedBy() != null
                    && linked.getApprovedBy().getId().equals(comm.getCreatedBy().getId());
            if (!autoGenerated && comm.getCreatedBy() != null && comm.getCreatedBy().getId().equals(approver.getId())) {
                throw new BusinessException("Quatro olhos: o aprovador deve ser diferente de quem criou a comunicacao");
            }
            if (linked != null && linked.getDecidedBy() != null
                    && linked.getDecidedBy().getId().equals(approver.getId())) {
                throw new BusinessException("Quatro olhos: o aprovador deve ser diferente de quem decidiu o case");
            }
        }
        String from = comm.getStatus();
        comm.setStatus("APPROVED");
        comm.setApprovedBy(approver);
        comm.setApprovedAt(Instant.now());
        comm = repository.save(comm);
        record(comm, "APPROVE", from, "APPROVED", just);
        AuditPayload.log(auditService, "SISCOAF_APPROVED", "SISCOAF_COMMUNICATION", comm.getId(),
                Map.of("status", from), Map.of("status", "APPROVED", "justification", just));
        return toListResponse(comm);
    }

    @Transactional
    public SiscoafResponse submit(UUID id) {
        return submit(id, null);
    }

    /**
     * Envio ao COAF: acao explicita de SUPERVISOR. COS/SAR exigem case com decisao COMMUNICATE
     * aprovada (decisao humana); nada e enviado automaticamente. Com quatro olhos exigido, a
     * comunicacao precisa estar APPROVED. A justificativa informada (opcional) vai ao historico.
     */
    @Transactional
    public SiscoafResponse submit(UUID id, String reason) {
        String just = reason == null || reason.isBlank() ? null : Justifications.require(reason, "envio ao COAF");
        SiscoafCommunication comm = repository.findById(id)
                .orElseThrow(() -> new BusinessException("Communication not found"));

        if (!"APPROVED".equals(comm.getStatus()) && !"DRAFT".equals(comm.getStatus())) {
            throw new BusinessException("Cannot submit in status: " + comm.getStatus());
        }
        if ("DRAFT".equals(comm.getStatus()) && fourEyesRequired(comm)) {
            throw new BusinessException(
                    "Quatro olhos: comunicacao de parte PEP/alto risco/EDD exige aprovacao previa (POST /siscoaf/{id}/approve)");
        }
        assertCosDecided(comm);
        Case linked = comm.getCaseEntity();

        String fromStatus = comm.getStatus();
        Instant now = Instant.now();
        if (comm.getApprovedBy() == null) {
            comm.setApprovedBy(currentUser.user().orElse(null));
            comm.setApprovedAt(now);
        }
        comm = orchestrator.submit(comm);
        comm.setSubmittedAt(now);
        comm = repository.save(comm);
        record(comm, "SUBMIT", fromStatus, comm.getStatus(), just);

        if (linked != null && "COMMUNICATE".equals(linked.getStatus())) {
            linked.setStatus("COMMUNICATED");
            linked.setClosedAt(now);
            caseRepository.save(linked);
        }

        Map<String, Object> audit = new LinkedHashMap<>();
        audit.put("status", comm.getStatus());
        audit.put("protocol", comm.getProtocolNumber());
        audit.put("late", comm.getDeadlineAt() != null && now.isAfter(comm.getDeadlineAt()));
        if (just != null) {
            audit.put("justification", just);
        }
        AuditPayload.log(auditService, "SISCOAF_SUBMIT", "SISCOAF_COMMUNICATION", comm.getId(),
                Map.of("status", fromStatus), audit);
        return toListResponse(comm);
    }

    @Transactional
    public SiscoafResponse cancel(UUID id, String reason) {
        String just = Justifications.require(reason, "cancelar comunicacao");
        SiscoafCommunication comm = repository.findById(id)
                .orElseThrow(() -> new BusinessException("Communication not found"));
        if (!CANCELLABLE.contains(comm.getStatus())) {
            throw new BusinessException("Comunicacao em status " + comm.getStatus()
                    + " nao pode ser cancelada (use retificacao)");
        }
        String from = comm.getStatus();
        comm.setStatus("CANCELLED");
        comm.setCancelledAt(Instant.now());
        comm.setCancelReason(just);
        comm = repository.save(comm);
        record(comm, "CANCEL", from, "CANCELLED", just);
        AuditPayload.log(auditService, "SISCOAF_CANCEL", "SISCOAF_COMMUNICATION", comm.getId(),
                Map.of("status", from), Map.of("status", "CANCELLED", "reason", just));
        return toListResponse(comm);
    }

    /** Retifica comunicacao ja enviada: marca a original como RECTIFIED e cria novo rascunho vinculado. */
    @Transactional
    public SiscoafResponse rectify(UUID id, String reason, Map<String, Object> newPayload) {
        String just = Justifications.require(reason, "retificar comunicacao");
        SiscoafCommunication original = repository.findById(id)
                .orElseThrow(() -> new BusinessException("Communication not found"));
        if (!SENT.contains(original.getStatus())) {
            throw new BusinessException("So comunicacoes enviadas podem ser retificadas");
        }
        String originalFrom = original.getStatus();
        original.setStatus("RECTIFIED");
        repository.saveAndFlush(original);
        record(original, "RECTIFY", originalFrom, "RECTIFIED", just);

        SiscoafCommunication copy = SiscoafCommunication.builder()
                .caseEntity(original.getCaseEntity())
                .party(original.getParty())
                .type(original.getType())
                .status("DRAFT")
                .payload(newPayload != null ? newPayload : original.getPayload())
                .deadlineAt(original.getDeadlineAt())
                .decidedAt(original.getDecidedAt())
                .referenceYear(original.getReferenceYear())
                .amount(original.getAmount())
                .indicatorCodes(original.getIndicatorCodes())
                .transaction(original.getTransaction())
                .originalCommunication(original)
                .createdBy(currentUser.user().orElse(null))
                .build();
        copy = repository.save(copy);
        record(copy, "CREATED_BY_RECTIFICATION", null, "DRAFT", just);
        AuditPayload.log(auditService, "SISCOAF_RECTIFY", "SISCOAF_COMMUNICATION", original.getId(),
                Map.of("status", "SUBMITTED"),
                Map.of("status", "RECTIFIED", "newCommunicationId", copy.getId().toString(), "reason", just));
        return toListResponse(copy);
    }

    @Transactional(readOnly = true)
    public Page<SiscoafResponse> findByStatus(String status, Pageable pageable) {
        return repository.findByStatus(status, pageable).map(SiscoafService::toResponse);
    }

    /** Listagem filtrada (status/tipo multiplos, periodo, parte, case). Sem historico (somente no detalhe). */
    @Transactional(readOnly = true)
    public Page<SiscoafResponse> findAll(SiscoafSpecifications.Filter filter, Pageable pageable) {
        return repository.findAll(SiscoafSpecifications.from(filter), pageable).map(this::toListResponse);
    }

    @Transactional(readOnly = true)
    public SiscoafResponse findById(UUID id) {
        SiscoafCommunication comm = repository.findById(id)
                .orElseThrow(() -> new IllegalArgumentException("Communication not found"));
        SiscoafResponse r = toListResponse(comm);
        r.setStatusHistory(history(comm));
        return r;
    }

    // ------------------------------------------------------------------ internos

    private void assertCosDecided(SiscoafCommunication comm) {
        if ("COS".equals(comm.getType()) || "SAR".equals(comm.getType())) {
            Case linked = comm.getCaseEntity();
            boolean decided = linked != null
                    && ("COMMUNICATE".equals(linked.getStatus()) || "COMMUNICATED".equals(linked.getStatus()));
            if (!decided) {
                throw new BusinessException(
                        "COS so pode ser enviada apos decisao humana COMMUNICATE aprovada no case");
            }
        }
    }

    /** Quatro olhos: parte PEP, risco alto/critico ou case EDD. */
    static boolean fourEyesRequired(SiscoafCommunication c) {
        Case k = c.getCaseEntity();
        Party p = c.getParty() != null ? c.getParty() : (k != null ? k.getParty() : null);
        if (k != null && k.isEdd()) {
            return true;
        }
        return p != null && (p.isPep() || "HIGH".equals(p.getRiskLevel()) || "CRITICAL".equals(p.getRiskLevel()));
    }

    private void record(SiscoafCommunication comm, String action, String from, String to, String comment) {
        historyRepository.save(SiscoafHistory.builder()
                .communication(comm).action(action).fromStatus(from).toStatus(to)
                .performedBy(currentUser.user().orElse(null)).comment(comment).build());
    }

    private List<SiscoafHistoryEntry> history(SiscoafCommunication comm) {
        List<SiscoafHistoryEntry> out = new ArrayList<>();
        var rows = historyRepository.findByCommunicationIdOrderByCreatedAtAsc(comm.getId());
        // comunicacoes criadas por outros fluxos (rascunho automatico, COE) nao gravam o evento inicial
        if (rows.stream().noneMatch(h -> h.getAction().startsWith("CREATED"))) {
            out.add(new SiscoafHistoryEntry("CREATED", "DRAFT", null,
                    comm.getCreatedBy() != null ? comm.getCreatedBy().getId() : null,
                    comm.getCreatedBy() != null ? comm.getCreatedBy().getName() : null, null, comm.getCreatedAt()));
        }
        for (SiscoafHistory h : rows) {
            out.add(new SiscoafHistoryEntry(h.getAction(), h.getToStatus(), h.getFromStatus(),
                    h.getPerformedBy() != null ? h.getPerformedBy().getId() : null,
                    h.getPerformedBy() != null ? h.getPerformedBy().getName() : null,
                    h.getComment(), h.getCreatedAt()));
        }
        return out;
    }

    private SiscoafResponse toListResponse(SiscoafCommunication c) {
        SiscoafResponse r = toResponse(c);
        Case k = c.getCaseEntity();
        Party p = c.getParty() != null ? c.getParty() : (k != null ? k.getParty() : null);
        r.setCaseNumber(k != null ? k.getCaseNumber() : null);
        r.setPartyName(p != null ? p.getName() : null);
        r.setPeriodFrom(k != null ? k.getPeriodStart() : null);
        r.setPeriodTo(k != null ? k.getPeriodEnd() : null);
        r.setCreatedById(c.getCreatedBy() != null ? c.getCreatedBy().getId() : null);
        r.setApprovedById(c.getApprovedBy() != null ? c.getApprovedBy().getId() : null);
        r.setFourEyesRequired(fourEyesRequired(c));
        return r;
    }

    /** Mapeamento basico (ids e campos escalares), seguro fora de transacao. */
    public static SiscoafResponse toResponse(SiscoafCommunication c) {
        return SiscoafResponse.builder()
                .id(c.getId())
                .caseId(c.getCaseEntity() != null ? c.getCaseEntity().getId() : null)
                .partyId(c.getParty() != null ? c.getParty().getId() : null)
                .transactionId(c.getTransaction() != null ? c.getTransaction().getId() : null)
                .originalCommunicationId(c.getOriginalCommunication() != null ? c.getOriginalCommunication().getId() : null)
                .type(c.getType())
                .status(c.getStatus())
                .protocolNumber(c.getProtocolNumber())
                .submittedAt(c.getSubmittedAt())
                .deadlineAt(c.getDeadlineAt())
                .decidedAt(c.getDecidedAt())
                .referenceYear(c.getReferenceYear())
                .amount(c.getAmount())
                .indicatorCodes(c.getIndicatorCodes())
                .cancelledAt(c.getCancelledAt())
                .cancelReason(c.getCancelReason())
                .approvedAt(c.getApprovedAt())
                .payload(c.getPayload())
                .createdAt(c.getCreatedAt())
                .build();
    }
}
